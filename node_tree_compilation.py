class NodeTreeCompiler:
    """Compiler for TGR node trees to generate UI code"""

    def __init__(self, layout_tree, armature):
        self.layout_tree = layout_tree
        self.armature = armature
        try:
            self.panel_nodes = [node for node in self.layout_tree.nodes if node.bl_idname == "TGR_LY_ND_Panel"]
        except AttributeError:
            self.panel_nodes = []
        try:
            self.callback_nodes = []
            for node in self.layout_tree.nodes:
                if node.bl_idname == "TGR_EX_Callback":
                    exists = any(callback_node.name == node.name for callback_node in self.callback_nodes)
                    if not exists:
                        self.callback_nodes.append(node)
        except AttributeError:
            self.callback_nodes = []
        try:
            self.operator_nodes = []
            for node in self.layout_tree.nodes:
                if node.bl_idname == "TGR_EX_Operator":
                    exists = any(operator_node.name == node.name for operator_node in self.operator_nodes)
                    if not exists:
                        self.operator_nodes.append(node)
        except AttributeError:
            self.operator_nodes = []
        try:
            self.property_group_nodes = []
            for node in self.layout_tree.nodes:
                if node.bl_idname == "TGR_DT_ND_PropertyGroup":
                    exists = any(property_group_node.name == node.name for property_group_node in self.property_group_nodes)
                    if not exists:
                        self.property_group_nodes.append(node)
        except AttributeError:
            self.property_group_nodes = []
        self.indent_level = 0
        self._generated_code = []

    @property
    def generated_code(self) -> str:
        return "\n".join(self._generated_code)

    def _indent(self) -> str:
        return "    " * self.indent_level

    def _new_line(self, line: str):
        self._generated_code.append(f"{self._indent()}{line}")

    def _set_boilerplate(self):
        """Set the boilerplate code for the generated script"""
        self._new_line("# This script is auto-generated by the Telergy Rigger UI Compiler")
        self._new_line("import bpy")
        self._new_line("from bpy.types import Panel, PropertyGroup")
        self._new_line("")
        self._new_line("")
        self._new_line("# =========================================================================")
        self._new_line("# Global Variables")
        self._new_line("# =========================================================================")
        self._new_line(f"ARMATURE_NAME = '{self.armature.name}'")
        self._new_line(f"ARMATURE = bpy.data.objects[ARMATURE_NAME]")

    def _set_classes_to_register(self):
        """Set the classes to register in the generated script"""
        self._new_line("# Add all the classes to register here:")
        self._new_line("CLASSES = [")
        self.indent_level += 1
        self._new_line("#Property Groups")
        for node in self.property_group_nodes:
            self._new_line(f"TGR_PG_{node.name.replace(' ', '_')},")
        self._new_line("#Operators")
        for node in self.operator_nodes:
            self._new_line(f"TGR_OT_{node.name.replace(' ', '_')},")
        self._new_line("#Panels")
        for node in self.panel_nodes:
            self._new_line(f"TGR_PT_{node.name.replace(' ', '_')},")
        self.indent_level -= 1
        self._new_line("]")

    def _value_node_string_get(self, value_node: Node) -> str:
        """Compile value nodes into Python code"""
        match value_node.bl_idname:
            case 'TGR_LY_ND_Value':
                return f"{value_node.value}"
            case 'TGR_LY_ND_CustomProp':
                if value_node.target.type != 'ARMATURE':
                    return f"bpy.data.objects['{value_node.target.name}']['{value_node.property_name}']"
                else:
                    return f"bpy.data.objects['{value_node.target.name}'].pose.bones['{value_node.subtarget}']['{value_node.property_name}']"
            case 'TGR_LY_ND_Prop':
                pass
            case 'TGR_ND_Float':
                return f"{value_node.default_value}"
            case 'TGR_ND_Integer':
                return f"{value_node.default_value}"
            case _:
                # TODO: Show the connection is not valid
                pass

    def _compile_compare_node(self, compare_node: Node) -> str:
        """Compile compare nodes into Python code"""
        try:
            value_a = self._value_node_string_get(compare_node.inputs[0].links[0].from_node)
            value_b = self._value_node_string_get(compare_node.inputs[1].links[0].from_node)
        except IndexError:
            print("[TGR COMPILE COMPARE] Both input nodes must be connected")
            return
        condition = ""
        match compare_node.operation:
            case 'EQUAL':
                condition = f"{value_a} == {value_b}"
                pass
            case 'NOT_EQUAL':
                condition = f"{value_a} != {value_b}"
                pass
            case 'LESS':
                condition = f"{value_a} < {value_b}"
                pass
            case 'GREATER':
                condition = f"{value_a} > {value_b}"
                pass
            case 'LESS_EQUAL':
                condition = f"{value_a} <= {value_b}"
                pass
            case 'GREATER_EQUAL':
                condition = f"{value_a} >= {value_b}"
                pass
            case 'EXPRESSION':
                if not (compare_node.inputs[0].is_linked or compare_node.inputs[1].is_linked):
                    # TODO: Both sockets must be linked
                    pass
                condition = f"{compare_node.expression}"
                condition = condition.replace('A', value_a)
                condition = condition.replace('B', value_b)
        if compare_node.outputs[0].links[0].to_node.bl_idname == 'TGR_FC_ND_If': 
            self._new_line(f"if {condition}:")
            self.indent_level += 1

        return condition
    
    def _get_bone_collection_condition(self, bone_collection_node: Node, socket: NodeSocket) -> str:
        """Get the condition for a bone collection node based on the connected socket"""
        if socket.name == "Is Visible":
            return f"ARMATURE.data.collections_all['{bone_collection_node.collection_name}'].is_visible"
        elif socket.name == "Is Solo":
            return f"ARMATURE.data.collections_all['{bone_collection_node.collection_name}'].is_solo"
        else:
            print(f"[TGR COMPILE BONE COLLECTION] Unsupported socket: {socket.name}")
            return None

    def _get_condition(self, node: Node, socket: NodeSocket) -> str:
        match node.bl_idname:
            case 'TGR_FC_ND_Compare':
                return self._compile_compare_node(node)
            case 'TGR_FC_ND_And':
                return self._compile_and_node(node, socket)
            case 'TGR_FC_ND_Or':
                return self._compile_or_node(node, socket)
            case 'TGR_FC_ND_Not':
                return self._compile_not_node(node, socket)
            case 'TGR_LY_ND_BoneCollection':
                return self._get_bone_collection_condition(node, socket)
            case _:
                print(f"[TGR COMPILE AND] Unsupported node type: {node.bl_idname}")
                return None

    def _compile_and_node(self, and_node: Node, socket: NodeSocket) -> str:
        """Compile AND nodes into Python code"""
        node_a = and_node.inputs[0].links[0].from_node if and_node.inputs[0].is_linked else None
        node_b = and_node.inputs[1].links[0].from_node if and_node.inputs[1].is_linked else None

        if not node_a or not node_b:
            print("[TGR COMPILE AND] Both input nodes must be connected")
            return

        socket_a = and_node.inputs[0].links[0].from_socket
        socket_b = and_node.inputs[1].links[0].from_socket

        condition_a = self._get_condition(node_a, socket_a)
        condition_b = self._get_condition(node_b, socket_b)

        return f"({condition_a}) and ({condition_b})"


    def _compile_or_node(self, or_node: Node, socket: NodeSocket) -> str:
        """Compile OR nodes into Python code"""
        node_a = or_node.inputs[0].links[0].from_node if or_node.inputs[0].is_linked else None
        node_b = or_node.inputs[1].links[0].from_node if or_node.inputs[1].is_linked else None

        if not node_a or not node_b:
            print("[TGR COMPILE OR] Both input nodes must be connected")
            return

        socket_a = or_node.inputs[0].links[0].from_socket
        socket_b = or_node.inputs[1].links[0].from_socket

        condition_a = self._get_condition(node_a, socket_a)
        condition_b = self._get_condition(node_b, socket_b)

        return f"({condition_a}) or ({condition_b})"


    def _compile_not_node(self, not_node: Node, socket: NodeSocket) -> str:
        """Compile NOT nodes into Python code"""
        input_node = not_node.inputs[0].links[0].from_node if not_node.inputs[0].is_linked else None

        if not input_node:
            print("[TGR COMPILE NOT] Input node must be connected")
            return

        socket = not_node.inputs[0].links[0].from_socket

        condition = self._get_condition(input_node, socket)

        return f"not ({condition})"
        

    def _compile_if(self, if_node: Node, parent_layout, level=0):
        """Compile if nodes into Python code"""
        true_node = if_node.inputs[1].links[0].from_node if if_node.inputs[1].is_linked else None
        false_node = if_node.inputs[2].links[0].from_node if if_node.inputs[2].is_linked else None
        if if_node.inputs[0].is_linked:
            condition_node = if_node.inputs[0].links[0].from_node
            if condition_node.bl_idname == 'TGR_FC_ND_Compare':
                self._compile_compare_node(condition_node, parent_layout, level)
                self._compile_layout_nodes(layout_node=true_node, parent_layout=parent_layout, level=level)
                self.indent_level -= 1
                self._new_line("else:")
                self.indent_level += 1
                self._compile_layout_nodes(layout_node=false_node, parent_layout=parent_layout, level=level)
                self.indent_level -= 1
            elif condition_node.bl_idname == 'TGR_LY_ND_BoneCollection':
                vis_condition = ""
                solo_condition = ""
                # Check which output is connected to the if node's input
                for socket in condition_node.outputs:
                    if not socket.is_linked:
                        continue
                    if socket.links[0].to_socket == if_node.inputs[0]:
                        if socket.name == "Is Visible":
                            vis_condition = f"ARMATURE.data.collections_all['{condition_node.collection_name}'].is_visible"
                        elif socket.name == "Is Solo":
                            solo_condition = f"ARMATURE.data.collections_all['{condition_node.collection_name}'].is_solo"

                if vis_condition:
                    condition = vis_condition
                elif solo_condition:
                    condition = solo_condition
                else:
                    # TODO: Show connection error
                    print("[TGR COMPILE IF] No valid output connected to the if node's input")
                    return
                
                self._new_line(f"if {condition}:")
                self.indent_level += 1
                if true_node and true_node.bl_idname != 'TGR_LY_ND_Empty':
                    self._compile_layout_nodes(layout_node=true_node, parent_layout=parent_layout, level=level)
                else:
                    self._new_line("pass")
                self.indent_level -= 1
                self._new_line("else:")
                self.indent_level += 1
                if false_node and false_node.bl_idname != 'TGR_LY_ND_Empty':
                    self._compile_layout_nodes(layout_node=false_node, parent_layout=parent_layout, level=level)
                else:
                    self._new_line("pass")
                self.indent_level -= 1

            elif condition_node.bl_idname in ['TGR_FC_ND_And', 'TGR_FC_ND_Or', 'TGR_FC_ND_Not']:
                condition = self._get_condition(condition_node, condition_node.outputs[0])
                self._new_line(f"if {condition}:")
                self.indent_level += 1
                if true_node and true_node.bl_idname != 'TGR_LY_ND_Empty':
                    self._compile_layout_nodes(layout_node=true_node, parent_layout=parent_layout, level=level)
                else:
                    self._new_line("pass")
                self.indent_level -= 1
                self._new_line("else:")
                self.indent_level += 1
                if false_node and false_node.bl_idname != 'TGR_LY_ND_Empty':
                    self._compile_layout_nodes(layout_node=false_node, parent_layout=parent_layout, level=level)
                else:
                    self._new_line("pass")
                self.indent_level -= 1

        else:
            if if_node.inputs[0].default_value:
                if not true_node:
                    return
                match true_node.outputs[0].bl_idname:
                    case 'TGR_SKT_Layout':
                        self._compile_layout_nodes(true_node, parent_layout, level)
            else:
                if not false_node:
                    return
                match false_node.outputs[0].bl_idname:
                    case 'TGR_SKT_Layout':
                        self._compile_layout_nodes(false_node, parent_layout, level)

    def _compile_float_data_node(self, float_node: Node) -> float:
        """Compile float data nodes into Python code"""
        if float_node.is_data:
            name = float_node.name.replace(' ', '_').replace('-', '_').replace('.', '_').lower()
            update_text = ""
            if float_node.inputs[0].is_linked:
                update_node = float_node.inputs[0].links[0].from_node
                update_text = f", update=tgr_{update_node.name.replace(' ', '_').replace('-', '_').replace('.', '_').lower()}"
